import { z } from 'zod';
import { BrowserCommand, BrowserCommandKind, BrowserEvent, BrowserResult } from './browser-commands.ts';

/**
 * The browser bridge: JSON text frames over a WebSocket on 127.0.0.1 between a browser extension
 * (the client) and the Ori Bot browser plugin (the server).
 *
 * The extension connects to `ws://127.0.0.1:<port>/` offering two subprotocols:
 * `BROWSER_BRIDGE_SUBPROTOCOL` and `LOOPBACK_TOKEN_PREFIX + <pairing token>`. The plugin refuses the
 * upgrade unless the token matches and the request comes from an extension origin, then answers with
 * `BROWSER_BRIDGE_SUBPROTOCOL`. The extension's first frame is `hello`; the plugin answers `welcome`.
 * Every `command` gets exactly one `result` with the same `id`. Either side may close at any time;
 * the extension reconnects.
 */
export const BROWSER_BRIDGE_PROTOCOL = 1;
export const BROWSER_BRIDGE_SUBPROTOCOL = 'morrowbot-browser.v1';
export const BROWSER_BRIDGE_DEFAULT_PORT = 47821;

/** The subprotocol entry that carries a loopback server's pairing token (`token.<token>`). */
export const LOOPBACK_TOKEN_PREFIX = 'token.';

/** A pairing token: 32 to 128 URL-safe characters, generated by the extension. */
export const PairingToken = z.string().regex(/^[A-Za-z0-9_-]{32,128}$/, 'Paste the pairing token from the browser extension (32 or more letters, digits, - or _)');

/** Origins of browser extensions, the only pages allowed to open the bridge. */
export const EXTENSION_ORIGIN = /^(chrome-extension|moz-extension|safari-web-extension):\/\/[A-Za-z0-9._-]+$/;

const Protocol = z.literal(BROWSER_BRIDGE_PROTOCOL);
const RequestNumber = z.number().int().nonnegative();

/** One installed copy of the extension, kept in its storage; the plugin gives it the same browser id each time it reconnects. */
export const ExtensionInstanceId = z.string().regex(/^[A-Za-z0-9_-]{16,64}$/);

export const BrowserFamily = z.enum(['chromium', 'firefox', 'safari']);
export type BrowserFamily = z.infer<typeof BrowserFamily>;

export const ExtensionMessage = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('hello'),
    protocol: Protocol,
    browser: z.strictObject({ family: BrowserFamily, name: z.string().min(1), version: z.string() }),
    extensionVersion: z.string().min(1),
    instanceId: ExtensionInstanceId,
    /** The commands this extension answers; any other gets `unsupported` from the plugin without asking. */
    commands: z.array(BrowserCommandKind),
  }),
  z.strictObject({ kind: z.literal('result'), id: RequestNumber, result: BrowserResult }),
  z.strictObject({ kind: z.literal('event'), event: BrowserEvent }),
  /** Keeps the connection (and a Manifest V3 service worker) alive; the plugin answers `pong`. */
  z.strictObject({ kind: z.literal('ping') }),
]);
export type ExtensionMessage = z.infer<typeof ExtensionMessage>;

export const PluginBridgeMessage = z.discriminatedUnion('kind', [
  z.strictObject({ kind: z.literal('welcome'), protocol: Protocol, browserId: z.string().min(1) }),
  z.strictObject({ kind: z.literal('command'), id: RequestNumber, command: BrowserCommand }),
  z.strictObject({ kind: z.literal('pong') }),
]);
export type PluginBridgeMessage = z.infer<typeof PluginBridgeMessage>;
